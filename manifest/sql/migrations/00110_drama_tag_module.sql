-- 短剧标签菜单（复用 tag 表 content_type=8）与短剧运营模块，对齐漫画/小说管理的四个子菜单。
-- +goose Up
CREATE TABLE drama_module (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id      bigint       NOT NULL DEFAULT 1,
    name         varchar(64)  NOT NULL,
    position     varchar(32)  NOT NULL DEFAULT '',
    style        smallint     NOT NULL DEFAULT 7,
    icon         smallint     NOT NULL DEFAULT 1,
    category_ids jsonb        NOT NULL DEFAULT '[]',
    tag_ids      jsonb        NOT NULL DEFAULT '[]',
    filter       jsonb        NOT NULL DEFAULT '{}',
    size         int          NOT NULL DEFAULT 9,
    rank         int          NOT NULL DEFAULT 0,
    status       smallint     NOT NULL DEFAULT 1,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_drama_module_repo ON drama_module (site_id, position, status, rank DESC, id DESC);
COMMENT ON TABLE drama_module IS '短剧分类运营模块(标题+样式+检索)';
COMMENT ON COLUMN drama_module.style IS '1=1大2小横图 2=2小横图 3=1大横图 4=2竖图 5=竖图横滑 6=横图横滑 7=竖图3X3';
COMMENT ON COLUMN drama_module.icon IS '1最新 2星星 3火';
COMMENT ON COLUMN drama_module.position IS 'cat_{分类ID}=H5 分类 Tab';

INSERT INTO admin_permission (parent_id, name, route_url, component, method, icon, is_menu, hide_in_menu, affix_tab, sort)
SELECT p.id, '短剧标签', '/drama/tag', 'content/drama-tag', '', 'lucide:tags', 1, 0, 0, 3
FROM admin_permission p
WHERE p.is_menu = 1 AND p.parent_id = 0 AND p.route_url = '/drama'
  AND NOT EXISTS (
      SELECT 1 FROM admin_permission x
      WHERE x.is_menu = 1 AND x.name = '短剧标签' AND x.route_url = '/drama/tag'
  )
LIMIT 1;

INSERT INTO admin_permission (parent_id, name, route_url, method, is_menu, sort)
SELECT m.id, v.name, v.route_url, v.method, 0, v.sort
FROM admin_permission m
CROSS JOIN (VALUES
    ('标签列表', '/backend/tag',      'GET',    1),
    ('新增标签', '/backend/tag',      'POST',   2),
    ('编辑标签', '/backend/tag/{id}', 'PUT',    3),
    ('删除标签', '/backend/tag/{id}', 'DELETE', 4)
) AS v(name, route_url, method, sort)
WHERE m.is_menu = 1 AND m.name = '短剧标签' AND m.route_url = '/drama/tag'
  AND NOT EXISTS (
      SELECT 1 FROM admin_permission x
      WHERE x.parent_id = m.id AND x.route_url = v.route_url AND x.method = v.method AND x.is_menu = 0
  );

