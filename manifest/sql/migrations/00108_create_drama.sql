-- 短剧：子站选用媒资后按集号同步入库；整部配默认付费，单集可覆盖，购买记录按单集 content_purchase.media_type=6。
-- +goose Up
CREATE TABLE drama (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id       bigint        NOT NULL DEFAULT 1,
    title         varchar(128)  NOT NULL,
    cover         varchar(500)  NOT NULL DEFAULT '',   -- 本站自定义封面，空则用媒资封面
    intro         varchar(1000) NOT NULL DEFAULT '',
    category      varchar(128)  NOT NULL DEFAULT '',   -- 本站分类，逗号分隔多选
    tags          jsonb         NOT NULL DEFAULT '[]',
    is_vip        smallint      NOT NULL DEFAULT 0,    -- 整部默认：1=非免费集为 VIP 集(与 price 互斥)
    price         numeric(14,2) NOT NULL DEFAULT 0,    -- 整部默认：非免费集的单集金币价
    free_episode  int           NOT NULL DEFAULT 1,    -- 前 N 集免费(集号 <= N)
    episode_count int           NOT NULL DEFAULT 0,    -- 媒资仍就绪的集数
    view_count    bigint        NOT NULL DEFAULT 0,
    buy_count     bigint        NOT NULL DEFAULT 0,
    like_count    bigint        NOT NULL DEFAULT 0,
    update_status smallint      NOT NULL DEFAULT 1,    -- 1连载 2完结
    rank          int           NOT NULL DEFAULT 0,
    is_recommend  smallint      NOT NULL DEFAULT 0,
    status        smallint      NOT NULL DEFAULT 0,    -- 0待上架 1上架 2下架
    media_code    varchar(32)   NOT NULL DEFAULT '',   -- 媒资中心整部短码
    created_at    timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz   NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_drama_media_code ON drama (site_id, media_code) WHERE media_code <> '';
CREATE INDEX idx_drama_list ON drama (site_id, status, rank DESC, id DESC);
CREATE INDEX idx_drama_tags ON drama USING GIN (tags);
COMMENT ON TABLE drama IS '短剧(本站选用的媒资整部)';

CREATE TABLE drama_episode (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id     bigint        NOT NULL DEFAULT 1,
    drama_id    bigint        NOT NULL,
    seq         int           NOT NULL,              -- 集号，从 1 起
    title       varchar(128)  NOT NULL DEFAULT '',
    media_code  varchar(32)   NOT NULL DEFAULT '',   -- 媒资中心剧集短码
    duration    int           NOT NULL DEFAULT 0,    -- 秒
    pay_mode    smallint      NOT NULL DEFAULT 0,    -- 0跟随整部 1免费 2金币 3VIP
    price       numeric(14,2) NOT NULL DEFAULT 0,    -- pay_mode=2 时的单集价，0 用整部价
    status      smallint      NOT NULL DEFAULT 1,    -- 本站 1上架 0下架
    media_ready smallint      NOT NULL DEFAULT 1,    -- 媒资侧仍就绪；同步时没了置 0，不删行
    created_at  timestamptz   NOT NULL DEFAULT now(),
    updated_at  timestamptz   NOT NULL DEFAULT now(),
    UNIQUE (site_id, drama_id, seq)
);
COMMENT ON TABLE drama_episode IS '短剧剧集(按集号同步，id 即单集购买 content_id)';

CREATE TABLE drama_category (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id    bigint      NOT NULL DEFAULT 1,
    name       varchar(32) NOT NULL,
    kind       smallint    NOT NULL DEFAULT 0,       -- 0普通 1新更 2推荐 3榜单
    rank       int         NOT NULL DEFAULT 0,
    status     smallint    NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (site_id, name)
);
CREATE INDEX idx_drama_category_repo ON drama_category (site_id, status, rank DESC, id DESC);
COMMENT ON TABLE drama_category IS '短剧分类(H5 顶栏 + 作品分类)';

