-- 已有视频管理权限的非超管角色，一并放开抖音菜单
UPDATE admin_role r
SET permissions = r.permissions || ',' || ids.joined
FROM (
    SELECT string_agg(p.id::text, ',') AS joined
    FROM admin_permission p
    WHERE (p.is_menu = 1 AND p.name IN ('抖音管理', '抖音列表', '抖音分类', '抖音标签')
           AND p.route_url IN ('/douyin', '/douyin/list', '/douyin/category', '/douyin/tag'))
       OR p.parent_id IN (
           SELECT id FROM admin_permission
           WHERE is_menu = 1 AND name IN ('抖音列表', '抖音分类', '抖音标签')
             AND route_url IN ('/douyin/list', '/douyin/category', '/douyin/tag')
       )
) ids
WHERE r.code <> 'superadmin'
  AND ids.joined IS NOT NULL
  AND EXISTS (
      SELECT 1 FROM admin_permission m
      WHERE m.is_menu = 1 AND m.name = '视频管理' AND m.route_url = '/video'
        AND (',' || r.permissions || ',') LIKE '%,' || m.id::text || ',%'
  );

