UPDATE admin_role r
SET permissions = trim(both ',' from r.permissions || ',' || ids.joined)
FROM (
    SELECT string_agg(p.id::text, ',') AS joined
    FROM admin_permission p
    WHERE (p.is_menu = 1 AND p.name IN ('视频模块', '动漫模块') AND p.route_url IN ('/video/module', '/cartoon/module'))
       OR p.parent_id IN (
           SELECT id FROM admin_permission
           WHERE is_menu = 1 AND name IN ('视频模块', '动漫模块')
             AND route_url IN ('/video/module', '/cartoon/module')
       )
) ids
WHERE r.code <> 'superadmin'
  AND ids.joined IS NOT NULL
  AND EXISTS (
      SELECT 1 FROM admin_permission m
      WHERE m.is_menu = 1 AND m.name IN ('视频管理', '动漫管理')
        AND (',' || r.permissions || ',') LIKE '%,' || m.id::text || ',%'
  );

