    site_id    bigint       NOT NULL DEFAULT 1,
    name       varchar(64)  NOT NULL,
    position   varchar(32)  NOT NULL DEFAULT 'cartoon_home',
    style      smallint     NOT NULL DEFAULT 2,
    icon       smallint     NOT NULL DEFAULT 1,
    tag_ids    jsonb        NOT NULL DEFAULT '[]',
    size       int          NOT NULL DEFAULT 6,
    rank       int          NOT NULL DEFAULT 0,
    status     smallint     NOT NULL DEFAULT 1,
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_cartoon_module_repo ON cartoon_module (site_id, position, status, rank DESC, id DESC);
COMMENT ON TABLE cartoon_module IS '动漫首页运营模块(标题+样式+标签检索)';

