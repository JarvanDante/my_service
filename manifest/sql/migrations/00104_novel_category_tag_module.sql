UPDATE admin_role r
SET permissions = trim(both ',' from r.permissions || ',' || ids.joined)
FROM (
    SELECT string_agg(p.id::text, ',') AS joined
    FROM admin_permission p
    WHERE (p.is_menu = 1 AND p.name IN ('小说分类', '小说标签', '小说模块')
           AND p.route_url IN ('/novel/category', '/novel/tag', '/novel/module'))
       OR p.parent_id IN (
           SELECT id FROM admin_permission
           WHERE is_menu = 1 AND name IN ('小说分类', '小说标签', '小说模块')
             AND route_url IN ('/novel/category', '/novel/tag', '/novel/module')
       )
) ids
WHERE r.code <> 'superadmin'
  AND ids.joined IS NOT NULL
  AND EXISTS (
      SELECT 1 FROM admin_permission m
      WHERE m.is_menu = 1 AND m.name = '小说管理'
        AND (',' || r.permissions || ',') LIKE '%,' || m.id::text || ',%'
  );

