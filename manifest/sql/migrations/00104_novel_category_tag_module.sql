-- 小说分类 / 标签菜单 / 运营模块, 对齐漫画管理四个子菜单。
-- kind: 0 普通分类(按名称筛作品)  1 新更  2 推荐  3 榜单。
-- +goose Up
CREATE TABLE novel_category (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id    bigint      NOT NULL DEFAULT 1,
    name       varchar(32) NOT NULL,
    kind       smallint    NOT NULL DEFAULT 0,
    rank       int         NOT NULL DEFAULT 0,
    status     smallint    NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (site_id, name)
);
CREATE INDEX idx_novel_category_repo ON novel_category (site_id, status, rank DESC, id DESC);
COMMENT ON TABLE novel_category IS '小说分类(H5 顶栏 + 作品分类)';

