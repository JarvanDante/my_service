INSERT INTO novel_category (site_id, name, kind, rank, status)
SELECT 1, t.category, 0, 50, 1
FROM (
    SELECT DISTINCT trim(category) AS category
    FROM novel
    WHERE category IS NOT NULL AND trim(category) <> ''
) t
WHERE NOT EXISTS (
    SELECT 1 FROM novel_category c WHERE c.site_id = 1 AND c.name = t.category
);

CREATE TABLE novel_module (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id      bigint       NOT NULL DEFAULT 1,
    name         varchar(64)  NOT NULL,
    position     varchar(32)  NOT NULL DEFAULT 'novel_home',
    style        smallint     NOT NULL DEFAULT 7,
    icon         smallint     NOT NULL DEFAULT 1,
    category_ids jsonb        NOT NULL DEFAULT '[]',
    tag_ids      jsonb        NOT NULL DEFAULT '[]',
    filter       jsonb        NOT NULL DEFAULT '{}',
    size         int          NOT NULL DEFAULT 9,
    rank         int          NOT NULL DEFAULT 0,
    status       smallint     NOT NULL DEFAULT 1,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_novel_module_repo ON novel_module (site_id, position, status, rank DESC, id DESC);
COMMENT ON TABLE novel_module IS '小说分类运营模块(标题+样式+检索)';
