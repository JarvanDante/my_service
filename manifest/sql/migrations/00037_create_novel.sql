-- 作品总字数与章节字数保持一致(与后台章节增删时的汇总口径相同)
UPDATE novel n SET word_count = (
    SELECT COALESCE(SUM(c.word_count), 0) FROM novel_chapter c
    WHERE c.site_id = n.site_id AND c.novel_id = n.id
) WHERE n.site_id = 1 AND n.title LIKE '样板小说%';

