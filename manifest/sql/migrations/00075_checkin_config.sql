ALTER TABLE checkin_reward
    ADD COLUMN IF NOT EXISTS label varchar(32) NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS points bigint NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS is_milestone smallint NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS ms_points bigint NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS ms_gold bigint NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS ms_vip_days int NOT NULL DEFAULT 0;
COMMENT ON COLUMN checkin_reward.points IS '普通签到积分';
COMMENT ON COLUMN checkin_reward.is_milestone IS '1=里程碑, 当天只发里程碑奖励';
COMMENT ON COLUMN checkin_reward.ms_points IS '里程碑积分';
COMMENT ON COLUMN checkin_reward.ms_gold IS '里程碑金币';
COMMENT ON COLUMN checkin_reward.ms_vip_days IS '里程碑VIP天数';

ALTER TABLE user_checkin
    ADD COLUMN IF NOT EXISTS reward_points bigint NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS reward_vip_days int NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS checkin_config (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id       bigint       NOT NULL DEFAULT 1,
    makeup_points int          NOT NULL DEFAULT 5,
    makeup_limit  int          NOT NULL DEFAULT 3,
    makeup_desc   varchar(64)  NOT NULL DEFAULT '',
    vip_group_id  bigint       NOT NULL DEFAULT 0,
    updated_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_checkin_config_site ON checkin_config (site_id);
COMMENT ON TABLE checkin_config IS '签到全局配置(补签/VIP组)';

