-- 已有 1/2/3/5/7 天补上积分与标签, 并补齐 1-15 天。
UPDATE checkin_reward SET
    label = '第' || day_num || '天',
    points = CASE day_num
        WHEN 1 THEN 10 WHEN 2 THEN 18 WHEN 3 THEN 26 WHEN 5 THEN 42 WHEN 7 THEN 50
        ELSE 10 + (day_num - 1) * 8 END,
    gold = CASE WHEN gold = 0 THEN day_num ELSE gold END
WHERE site_id = 1 AND user_type = 0;

INSERT INTO checkin_reward (site_id, day_num, user_type, label, points, gold, vip_days, is_milestone, status)
SELECT 1, d, 0, '第' || d || '天',
       CASE WHEN d = 15 THEN 150 ELSE 10 + (d - 1) * 8 END,
       d,
       CASE WHEN d = 7 THEN 3 WHEN d = 14 THEN 3 ELSE 0 END,
       0, 1
FROM generate_series(1, 15) AS d
WHERE NOT EXISTS (
    SELECT 1 FROM checkin_reward r
    WHERE r.site_id = 1 AND r.user_type = 0 AND r.day_num = d
);

UPDATE checkin_reward SET
    is_milestone = 1, ms_points = 22, ms_gold = 12, ms_vip_days = 12, vip_days = 0
WHERE site_id = 1 AND user_type = 0 AND day_num = 8;

